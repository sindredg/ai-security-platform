"""Write the test evidence pages from their records, or check them.

    render.py [--check]

Reads each run set under `docs/evidence/records/` and the lessons in
`records/lessons.json`, and writes beside the records' folder a page per run
set, the lessons page, and the index. With `--check`, writes nothing and exits
1 when a page differs from what its record gives, or when a page is missing or
left over.

Fails before writing anything when a record lacks a field the pages use, when
a lesson names a run set or job that has no record, when a record holds
something that must not be published (an address outside private ranges, a
GUID, a long hex string, a home directory, an email address, a private key),
or when a page would break the page rules: a table of more than five columns,
a cell of 30 words or more, a paragraph of more than three sentences, or an em
dash. The model's answers are quoted as they are, in code blocks, which the
page rules skip. Standard library only.
"""

import ipaddress
import json
import re
import statistics
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NOTE = "<!-- Generated by validation/evidence/render.py from {}. Edit the record. -->"
DIAGRAM = "../diagrams/test-outcomes.svg"

SET_FIELDS = (
    "title",
    "short",
    "milestone",
    "tested",
    "changed",
    "setup",
    "source",
    "links",
)
JOB_FIELDS = ("job", "started", "finished", "phase", "steps", "calls", "answer")
CAUSES = {
    "mismatch": "wrong verdict",
    "no-verdict": "no verdict line",
    "checks-disagree": "checks disagree",
    "inconclusive": "inconclusive verdict",
    "lines-disagree": "verdict lines disagree",
    "checks-unknown": "checks cannot settle it",
}
UNREAD = re.compile(r"^verdict lines that could not be read: (\d+)$")
DENY = (
    (
        re.compile(r"\b[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}\b", re.IGNORECASE),
        "a GUID",
    ),
    (re.compile(r"\b[0-9a-f]{32,}\b", re.IGNORECASE), "a long hex string"),
    (re.compile(r"/home/|/Users/|C:\\Users"), "a home directory"),
    (re.compile(r"\b[\w.+-]+@[\w-]+(?:\.[\w-]+)+\b"), "an email address"),
    (re.compile(r"-----BEGIN"), "a private key"),
)
IPV4 = re.compile(r"\b\d{1,3}(?:\.\d{1,3}){3}\b")
SENTENCE_END = re.compile(r"[.!?][)*`\"']*\s+(?=[A-Z`*\[(\"'])")
FENCE = re.compile(r"^(`{3,}|~{3,})")


def strings(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for item in value.values():
            yield from strings(item)
    elif isinstance(value, list):
        for item in value:
            yield from strings(item)


def unpublishable(text):
    found = [label for pattern, label in DENY if pattern.search(text)]
    for match in IPV4.findall(text):
        try:
            if not ipaddress.ip_address(match).is_private:
                found.append(f"a public address, {match}")
        except ValueError:
            pass
    return found


def validate(name, run_set):
    problems = [f"{name}: no {f}" for f in SET_FIELDS if f not in run_set]
    for job in run_set.get("jobs", []):
        missing = [f for f in JOB_FIELDS if f not in job]
        problems += [f"{name}: {job.get('job')}: no {f}" for f in missing]
    for text in strings(run_set):
        problems += [f"{name}: holds {label}" for label in unpublishable(text)]
    return problems


def clock(stamp):
    return datetime.fromisoformat(stamp) if stamp else None


def anchor(heading):
    return re.sub(r"[^a-z0-9 _-]", "", heading.lower()).replace(" ", "-")


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + " --- |" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def fence(text):
    longest = max((len(m) for m in re.findall(r"`+|~+", text)), default=0)
    return "`" * max(3, longest + 1)


def quoted(text, summary):
    mark = fence(text)
    return [
        "<details>",
        f"<summary>{summary}</summary>",
        "",
        mark + "text",
        text.rstrip("\n"),
        mark,
        "",
        "</details>",
        "",
    ]


# Run sets of dispatched jobs


def labels(jobs):
    """A label per job: its case and the run, or the job's name."""
    seen, found = {}, {}
    for job in jobs:
        if job.get("case"):
            seen[job["case"]] = seen.get(job["case"], 0) + 1
            found[job["job"]] = f"{job['case']} {seen[job['case']]}"
        else:
            found[job["job"]] = job["job"]
    return found


def failed_step(job):
    return next((s for s in job["steps"] if s["phase"] in ("Failed", "Error")), None)


def stop_causes(comparison):
    causes = []
    for row in comparison["accounts"]:
        cause = CAUSES.get(row["outcome"])
        if cause and cause not in causes:
            causes.append(cause)
    for reason in comparison["reasons"]:
        if match := UNREAD.match(reason):
            count = int(match[1])
            causes.append(f"{count} unreadable line{'s' if count > 1 else ''}")
        elif "not an account the checks name" in reason:
            causes.append("a line for another account")
        elif reason == "no checks' verdicts for this job":
            causes.append("no checks' verdicts")
    return causes or comparison["reasons"]


def outcome(job):
    """The job's outcome in a few words."""
    comparison, step = job.get("comparison"), failed_step(job)
    result = job.get("result") or {}
    message = job.get("message") or ""
    if job["phase"] is None:
        return {"completed": "Completed", "cancelled": "Cancelled"}.get(
            result.get("status"), "Not known"
        )
    if job["phase"] == "Succeeded":
        if comparison and comparison["outcome"] == "match":
            return "Match"
        return "Completed"
    if message.startswith("Stopped with strategy"):
        return "Stopped"
    if step and step["step"] == "compare" and comparison:
        return "Stop: " + ", ".join(stop_causes(comparison))
    if step and step["step"] == "dispatch":
        if result.get("status") == "timeout":
            return "Failed: time limit reached"
        return "Failed at dispatch"
    if not job["steps"]:
        return "Refused"
    return f"{job['phase']}"


def verdicts_right(job):
    checks = job.get("checks")
    if not checks:
        return "No checks"
    agreed = sorted(a for a, (c, o) in checks.items() if c == o)
    rows = {r["account"]: r for r in (job.get("comparison") or {}).get("accounts", [])}
    right = sum(1 for a in agreed if rows.get(a, {}).get("model") == checks[a][0])
    return f"{right} of {len(agreed)}"


def call_count(job):
    """The calls, with how many were refused or went to Goose's own tools."""
    kinds = {
        "refused": "refused",
        "goose": "to Goose's own tools",
        "missing": "unlogged",
    }
    extra = [
        f"{n} {label}"
        for kind, label in kinds.items()
        if (n := sum(1 for c in job["calls"] if c["decision"] == kind))
    ]
    return ", ".join([str(len(job["calls"])), *extra])


def minutes(job):
    start, end = clock(job["started"]), clock(job["finished"])
    if not (start and end):
        return "Not known"
    return f"{(end - start).total_seconds() / 60:.1f}"


def verdict_table(job):
    checks = job.get("checks") or {}
    rows = {r["account"]: r for r in (job.get("comparison") or {}).get("accounts", [])}
    body = []
    for account in sorted(checks):
        row = rows.get(account)
        if row and row["model"]:
            cited = ", ".join(row["references"]) or "nothing"
            model = f"`{row['model']}`, citing {cited}"
        else:
            model = "None"
        configured, observed = (f"`{v}`" for v in checks[account])
        done = row["outcome"] if row else "Not compared"
        body.append([f"`{account}`", model, configured, observed, done])
    header = ["Account", "The model's verdict", "Configured", "Observed", "Outcome"]
    return [table(header, body), ""]


def call_table(job):
    body = []
    for n, call in enumerate(job["calls"], 1):
        result = {
            "allowed": f"Allowed, {call['bytes'] or 0:,} bytes",
            "refused": f"Refused: {call['reason']}",
            "goose": "Goose's own tool. The tool service never saw it",
            "missing": "Not in the audit log",
        }[call["decision"]]
        at = f"{clock(call['at']):%H:%M:%S}" if call["at"] else "Not logged"
        body.append([n, at, f"`{call['tool']}`", f"`{call['argument']}`", result])
    return [table(["Call", "Time (UTC)", "Tool", "Argument", "Result"], body), ""]


def worker_line(result):
    if result.get("output_tokens") is not None:
        tokens = (
            f"{result['input_tokens']:,} tokens in and {result['output_tokens']:,} out"
        )
    else:
        tokens = "no token counts"
    seconds = f" after {result['seconds']} s" if result.get("seconds") else ""
    erased = {
        True: ", the model's slot erased after it",
        False: ", the slot not erased",
    }
    return (
        f"On the worker: `{result['status']}`{seconds}, {tokens}"
        f"{erased.get(result.get('slot_erased'), '')}."
    )


def job_section(job, label):
    out = [f"## {label}", ""]
    start, end = clock(job["started"]), clock(job["finished"])
    if start and end:
        when = f"{start:%Y-%m-%d %H:%M:%S} to {end:%H:%M:%S} UTC"
    elif end:
        when = f"ended {end:%Y-%m-%d %H:%M:%S} UTC"
    else:
        when = "times not kept"
    out += [f"`{job['job']}`, {when}. **{outcome(job)}.**", ""]
    if job.get("note"):
        out += [job["note"], ""]
    reasons = (job.get("comparison") or {}).get("reasons") or []
    step = failed_step(job)
    if reasons:
        out += ["The comparison's reasons:", ""] + [f"- `{r}`" for r in reasons] + [""]
    elif step and step["message"]:
        out += [f"The `{step['step']}` step's message: `{step['message']}`.", ""]
    elif job.get("message"):
        out += [f"The workflow's message: `{job['message']}`.", ""]
    if job.get("checks"):
        out += verdict_table(job)
    out += call_table(job) if job["calls"] else ["No tool call.", ""]
    if job.get("result"):
        out += [worker_line(job["result"]), ""]
    answer = job["answer"]
    if answer:
        out += quoted(answer, f"The answer, {len(answer.encode()):,} bytes")
    elif answer is None:
        out += ["The answer was not kept.", ""]
    else:
        out += ["No answer.", ""]
    return out


def jobs_body(run_set):
    jobs = run_set["jobs"]
    names = labels(jobs)
    rows = [
        [
            f"[{names[j['job']]}](#{anchor(names[j['job']])})",
            outcome(j),
            verdicts_right(j),
            call_count(j),
            minutes(j),
        ]
        for j in jobs
    ]
    out = ["## Outcomes", ""]
    out += [table(["Job", "Outcome", "Verdicts right", "Calls", "Minutes"], rows), ""]
    out += [
        (
            "Verdicts right counts the accounts whose two checks agree. Minutes run "
            "from the workflow's start to its end."
        ),
        "",
    ]
    return out, [line for j in jobs for line in job_section(j, names[j["job"]])]


def jobs_tally(run_set):
    counts = {}
    for job in run_set["jobs"]:
        word = outcome(job).split(":")[0].lower()
        counts[word] = counts.get(word, 0) + 1
    return ", ".join(f"{n} {word}" for word, n in counts.items())


# Run sets of model comparison cases


def answer_summary(case, run):
    """A wrong answer in a few words: status, excess, and what else was off."""
    verdict = run["verdict"] or {}
    excess = [
        f"`{e}`" if len(e.split()) <= 3 else "a sentence" for e in verdict["excess"]
    ]
    parts = [f"`{verdict.get('status')}`, " + (", ".join(excess) or "no excess")]
    finding = str(verdict.get("finding"))
    if finding != case["finding"]:
        if re.fullmatch(r"F-\d{4}", finding):
            parts.append(f"`finding` is `{finding}`")
        elif finding.lower() in ("confirmed", "refuted", "inconclusive"):
            parts.append("`finding` holds the status")
        else:
            parts.append("`finding` holds a sentence")
    asked, wanted = run["asked"] or [], case["references"]
    extra = [a for a in asked if a not in wanted]
    if len(extra) > 2:
        parts.append(f"asked for {len(extra)} more references")
    elif extra:
        parts.append("also asked for " + ", ".join(f"`{a}`" for a in extra))
    missed = [w for w in wanted if w not in asked]
    if missed:
        parts.append("never asked for " + ", ".join(f"`{m}`" for m in missed))
    return ". ".join(parts)


def cases_body(run_set):
    cases = {c["case"]: c for c in run_set["cases"]}
    models = run_set["models"]
    summary = []
    for model in models:
        runs = model["runs"]
        right = sum(1 for r in runs if r["ok"])
        median = statistics.median(r["seconds"] for r in runs)
        summary.append([model["model"], f"{right} of {len(runs)}", f"{median:.1f}"])
    out = ["## Cases right", ""]
    out += [table(["Model", "Cases right", "Median seconds per case"], summary), ""]
    rows = []
    for name, case in cases.items():
        correct = ", ".join(f"`{e}`" for e in case["excess"]) or "none"
        row = [name, f"`{case['status']}`, {correct}"]
        for model in models:
            runs = [r for r in model["runs"] if r["case"] == name]
            texts = ["Right" if r["ok"] else answer_summary(case, r) for r in runs]
            if len(set(texts)) == 1:
                row.append(texts[0])
            else:
                row.append(
                    "; ".join(f"run {r['run']}: {t}" for r, t in zip(runs, texts))
                )
        rows.append(row)
    out += ["## Answers", ""]
    out += [table(["Case", "Right answer", *(m["model"] for m in models)], rows), ""]
    out += [
        (
            "A case is right when the model asks for exactly the case's references "
            "and answers with the finding, the status, and the excess. The same "
            "answer in both runs is shown once."
        ),
        "",
    ]
    details = []
    for model in models:
        wrong = {}
        for run in model["runs"]:
            if not run["ok"] and run["verdict"]:
                given = json.dumps(
                    {"asked": run["asked"], **run["verdict"]}, ensure_ascii=False
                )
                wrong.setdefault((run["case"], given), []).append(str(run["run"]))
        if wrong:
            text = "\n".join(
                f"{case}, run {' and '.join(runs)}: {given}"
                for (case, given), runs in wrong.items()
            )
            details += quoted(text, f"{model['model']}: the wrong answers, as given")
    return out, details


def cases_tally(run_set):
    rights = [sum(1 for r in m["runs"] if r["ok"]) for m in run_set["models"]]
    total = len(run_set["models"][0]["runs"])
    return (
        ", ".join(str(r) for r in rights[:-1]) + f", and {rights[-1]} of {total} right"
    )


# Pages


def set_page(name, run_set, previous, following):
    nav = ["[All run sets](README.md)"]
    if previous:
        nav.append(f"[previous: {previous[1]['short']}]({previous[0]}.md)")
    if following:
        nav.append(f"[next: {following[1]['short']}]({following[0]}.md)")
    out = [NOTE.format(f"records/{name}.json"), "", f"# {run_set['title']}", ""]
    out += [
        f"Milestone {run_set['milestone']}, {name[:10]}. " + ", ".join(nav) + ".",
        "",
    ]
    out += [f"**Tested:** {run_set['tested']}", ""]
    out += [f"**Changed since the run set before:** {run_set['changed']}", ""]
    out += [table(["Setting", "Value"], run_set["setup"]), ""]
    if run_set.get("kind") == "cases":
        body, details = cases_body(run_set)
    else:
        body, details = jobs_body(run_set)
    out += body
    if run_set.get("diagram"):
        alt, src = run_set["diagram"]
        out += [f"![{alt}]({src})", ""]
    out += [f"**Source:** {run_set['source']}", ""]
    out += [
        "**Also:** " + ", ".join(f"[{t}]({u})" for t, u in run_set["links"]) + ".",
        "",
    ]
    return "\n".join(out + details).rstrip("\n") + "\n"


def index_page(sets):
    out = [NOTE.format("records/"), "", "# Test evidence", ""]
    out += [
        (
            "Each run set is a batch of agent jobs, or model calls, that tested one "
            "thing. Its page gives each job's answer, its verdicts beside the "
            "checks', why it stopped, and its tool calls in order. "
            "[Lessons](lessons.md) says what the runs showed and what changed "
            "because of them."
        ),
        "",
        f"![NetBox jobs at the comparison, per run set: matches, stops by their cause, and failures]({DIAGRAM})",
        "",
    ]
    rows = []
    for name, run_set in sets:
        if run_set.get("kind") == "cases":
            count = f"{len(run_set['cases'])} cases, {len(run_set['models'])} models"
            tally = cases_tally(run_set)
        else:
            count, tally = len(run_set["jobs"]), jobs_tally(run_set)
        title = f"[{run_set['title']}]({name}.md)"
        rows.append([title, name[:10], run_set["tested"], count, tally])
    out += [table(["Run set", "Date", "Tested", "Jobs", "Outcomes"], rows), ""]
    out += [
        (
            "Each run set has one record in [`records/`](records/), built from each "
            "workflow and the tool service's audit log by "
            "[`record.py`](../../validation/evidence/record.py). The pages are "
            "generated from the records, and the pipeline fails when a page and "
            "its record differ. How a run set is recorded is in the "
            "[runbook](../runbooks/test-evidence.md)."
        ),
        "",
    ]
    return "\n".join(out)


def lessons_page(lessons, sets):
    names = dict(sets)
    problems, rows = [], []
    for lesson in lessons["lessons"]:
        links = []
        for ref in lesson["runs"]:
            set_name, _, job = ref.partition("#")
            run_set = names.get(set_name)
            jobs = labels(run_set.get("jobs", [])).values() if run_set else []
            known = {anchor(label): label for label in jobs}
            if run_set is None or (job and job not in known):
                problems.append(f"lessons.json: no run set or job {ref}")
                continue
            text = f"{run_set['short']}, {known[job]}" if job else run_set["short"]
            links.append(f"[{text}]({set_name}.md{'#' + job if job else ''})")
        rows.append([lesson["finding"], ", ".join(links), lesson["change"]])
    out = [NOTE.format("records/lessons.json"), "", "# Lessons", ""]
    out += [lessons["intro"], ""]
    out += [table(["Finding", "Runs that show it", "What changed"], rows), ""]
    return "\n".join(out), problems


def page_problems(name, text):
    """The page rules, outside code blocks and HTML lines."""
    problems, paragraph, in_code = [], [], None

    def close():
        if paragraph:
            joined = " ".join(paragraph)
            count = len(SENTENCE_END.findall(joined + " X")) or 1
            if count > 3:
                problems.append(
                    f"{name}: a paragraph of {count} sentences: {joined[:60]}"
                )
            paragraph.clear()

    for line in text.splitlines():
        stripped = line.strip()
        if in_code:
            if stripped == in_code:
                in_code = None
            continue
        if match := FENCE.match(stripped):
            close()
            in_code = match[1]
            continue
        if "\u2014" in line:
            problems.append(f"{name}: an em dash: {stripped[:60]}")
        if stripped.startswith("|"):
            close()
            cells = [c.strip() for c in stripped.strip("|").split("|")]
            if len(cells) > 5:
                problems.append(f"{name}: a table of {len(cells)} columns")
            problems += [
                f"{name}: a cell of {len(c.split())} words: {c[:40]}"
                for c in cells
                if len(c.split()) >= 30
            ]
        elif not stripped or stripped.startswith(("<", "#", "!")):
            close()
        elif re.match(r"^([-*]|\d+\.) ", stripped):
            close()
            paragraph.append(stripped)
        else:
            paragraph.append(stripped)
    close()
    return problems


def pages(root=ROOT):
    records = root / "docs" / "evidence" / "records"
    sets = [
        (p.stem, json.loads(p.read_text()))
        for p in sorted(records.glob("*.json"))
        if p.name != "lessons.json"
    ]
    problems = [m for name, s in sets for m in validate(name, s)]
    if problems:
        return {}, problems
    written = {}
    for i, (name, run_set) in enumerate(sets):
        previous = sets[i - 1] if i else None
        following = sets[i + 1] if i + 1 < len(sets) else None
        written[f"{name}.md"] = set_page(name, run_set, previous, following)
    written["README.md"] = index_page(sets)
    lessons_file = records / "lessons.json"
    if lessons_file.exists():
        lessons = json.loads(lessons_file.read_text())
        problems += [
            f"lessons.json: holds {x}"
            for t in strings(lessons)
            for x in unpublishable(t)
        ]
        written["lessons.md"], found = lessons_page(lessons, sets)
        problems += found
    for page, text in written.items():
        problems += page_problems(page, text)
    return written, problems


def main(argv, root=ROOT):
    check = argv[1:] == ["--check"]
    if argv[1:] and not check:
        print(__doc__.split("\n\n")[1], file=sys.stderr)
        return 2
    written, problems = pages(root)
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    folder = root / "docs" / "evidence"
    if check:
        stale = sorted(
            page
            for page, text in written.items()
            if not (folder / page).exists() or (folder / page).read_text() != text
        )
        extra = sorted({p.name for p in folder.glob("*.md")} - set(written))
        for page in stale:
            print(f"out of date: docs/evidence/{page}", file=sys.stderr)
        for page in extra:
            print(f"no record for: docs/evidence/{page}", file=sys.stderr)
        return 1 if stale or extra else 0
    for page, text in written.items():
        (folder / page).write_text(text)
    print(f"wrote {len(written)} pages")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
